// ----------------------------------------------------------------------------
// INITIALISATION DU GOBELIN
// ----------------------------------------------------------------------------

func InitGoblin() Monster {
	return Monster{
		Name:      "Gobelin d'entrainement",
		MaxHP:     40,
		CurrentHP: 40,
		Attack:    5,
	}
}

// ----------------------------------------------------------------------------
// TOUR DU GOBELIN
// ----------------------------------------------------------------------------

func GoblinPattern(goblin *Monster, player *Character, turn int) {
	fmt.Printf("\n--- Tour de %s ---\n", goblin.Name)
	fmt.Println(GetASCII(goblin.Name))

	damage := goblin.Attack
	if turn%3 == 0 {
		damage = goblin.Attack * 2
		fmt.Println("⚡ Le Gobelin prépare une attaque puissante !")
	}

	player.CurrentHP -= damage
	if player.CurrentHP < 0 {
		player.CurrentHP = 0
	}

	fmt.Printf("%s inflige à %s %d de dégâts.\n", goblin.Name, player.Name, damage)
	fmt.Printf("%s PV : %d / %d\n", player.Name, player.CurrentHP, player.MaxHP)
	time.Sleep(1 * time.Second)
}

// ----------------------------------------------------------------------------
// TOUR DU JOUEUR
// ----------------------------------------------------------------------------

func CharacterTurn(player *Character, goblin *Monster) {
	fmt.Printf("\n--- Tour de %s (%s) ---\n", player.Name, player.Class)
	fmt.Println(GetASCII(player.Class))

	for {
		fmt.Println("\n=== MENU COMBAT ===")
		fmt.Println("1. Attaquer")
		fmt.Println("2. Inventaire")
		fmt.Print("Choisissez une action : ")

		var choice int
		fmt.Scanln(&choice)

		if choice == 1 {
			damage := 5
			goblin.CurrentHP -= damage
			if goblin.CurrentHP < 0 {
				goblin.CurrentHP = 0
			}
			fmt.Printf("\n%s utilise Attaque basique et inflige %d dégâts à %s !\n", player.Name, damage, goblin.Name)
			fmt.Printf("%s PV : %d / %d\n", goblin.Name, goblin.CurrentHP, goblin.MaxHP)
			time.Sleep(1 * time.Second)
			break

		} else if choice == 2 {
			if len(player.Inventory) == 0 {
				fmt.Println("Votre inventaire est vide !")
				continue
			}

			fmt.Println("\n--- Inventaire ---")
			for i, item := range player.Inventory {
				fmt.Printf("%d. %s\n", i+1, item)
			}
			fmt.Println("0. Retour")
			fmt.Print("Choisissez un objet à utiliser : ")

			var itemChoice int
			fmt.Scanln(&itemChoice)

			if itemChoice == 0 {
				continue
			}

			if itemChoice > 0 && itemChoice <= len(player.Inventory) {
				item := player.Inventory[itemChoice-1]

				if item == "Potion de vie" {
					player.CurrentHP += 50
					if player.CurrentHP > player.MaxHP {
						player.CurrentHP = player.MaxHP
					}
					fmt.Printf("\nVous utilisez une Potion de vie. PV actuels : %d / %d\n", player.CurrentHP, player.MaxHP)

					player.Inventory = append(player.Inventory[:itemChoice-1], player.Inventory[itemChoice:]...)
					time.Sleep(1 * time.Second)
					break
				} else {
					fmt.Println("Cet objet ne peut pas être utilisé en combat.")
				}
			} else {
				fmt.Println("Choix invalide.")
			}
		} else {
			fmt.Println("Option invalide, réessayez.")
		}
	}
}

// ----------------------------------------------------------------------------
// BOUCLE PRINCIPALE DE COMBAT
// ----------------------------------------------------------------------------

func TrainingFight(player *Character) {
	goblin := InitGoblin()
	turn := 1

	fmt.Println("\n========================================")
	fmt.Printf("   DEBUT DU COMBAT : %s vs %s   \n", player.Name, goblin.Name)
	fmt.Println("========================================")

	for player.CurrentHP > 0 && goblin.CurrentHP > 0 {
		fmt.Printf("\n========== TOUR %d ==========\n", turn)

		// Tour du joueur
		CharacterTurn(player, &goblin)
		if goblin.CurrentHP <= 0 {
			fmt.Printf("\n🎉 Félicitations ! Vous avez vaincu %s !\n", goblin.Name)
			break
		}

		// Tour du monstre
		GoblinPattern(&goblin, player, turn)
		if player.CurrentHP <= 0 {
			fmt.Printf("\n☠️ Vous avez été vaincu par %s...\n", goblin.Name)
			break
		}

		turn++
	}

	if player.CurrentHP <= 0 {
		fmt.Println("Vous êtes ressuscité avec 50% de vos PV max.")
		player.CurrentHP = player.MaxHP / 2
	}
}
